/// Как подаются данные. Одинаково для всех ролей.
macro_rules! how_data_is_given {
    () => {
        "\
Как подаются данные:
• «Что известно» — можно называть прямо, если ложится в текст естественно.
• «Как писать» (фон) — определяет, каким человек получится, но называть это
  прямо нельзя. Характер чувствуется в тоне, а не объявляется. Происхождение
  влияет на имя и внешность, но фраза о нём неуместна. Детство, родители,
  увлечения — не больше одной детали и только если она работает на историю.
  ЧИСЛА ИЗ БЛОКА «КАК ПИСАТЬ» ПЕРЕНОСИТЬ В ТЕКСТ ЗАПРЕЩЕНО.
• «Обязательно упомянуть» — должно прозвучать.
"
    };
}

/// Требования к тексту. Одинаково для всех ролей.
macro_rules! text_rules {
    () => {
        "\
Жёсткие требования:
1. Не меняй и не округляй заданные числа. Стаж 18 лет — не «около двадцати».
2. Не добавляй фактов, которых нет в данных: ни мест работы, ни наград, ни
   методик, ни цифр, ни городов.
3. ИМЯ ЗАДАНО. Полностью назови его один раз; дальше — по имени и отчеству,
   по фамилии или местоимением. Своё имя не выдумывай. Имя склоняй по падежам:
   «для Степанова Виктора Владимировича», а не «для Степанов Виктор
   Владимирович».
4. ВОЗРАСТ — ТОЛЬКО НЫНЕШНИЙ. О прошлом говори через этапы и «сколько лет
   назад»: «после ординатуры», «восемь лет назад», «когда работал на скорой».
   Не пиши «в 62 года пришёл в профессию», если этого возраста нет в данных:
   нынешний возраст к прошлому событию не относится. Отдельной фразой
   «Сейчас ему 48 лет» возраст не сообщай.
5. Не выстраивай текст как анкету: не перечисляй пункты подряд.
   Плохо: «Вырос в районном центре. Родители инженеры. Увлекается бегом.»
   Хорошо: рассказ о том, как человек пришёл к этой работе и как её делает.
6. ЗАЧИН — как указано в «Как писать» (с чего начать). Не начинай с «ФИО
   вырос…», «ФИО родился…» или «ФИО пришёл…»: так начинаются тысячи соседних
   карточек. ФИО — внутри первой фразы, а не первым словом.
7. Не перечисляй, чего человек НЕ делает. Отсутствующий признак означает
   «об этом не писать», а не «написать, что этого нет».
8. Никаких рекламных оборотов («ведущий специалист», «уникальная методика»),
   канцелярита и обещаний вылечить.
9. Цитата — живая речь этого человека, одна-две фразы, как сказал бы он сам
   в разговоре. Не афоризм и не плакат: никаких «каждый заслуживает второй
   шанс», «свет в конце тоннеля», «главное — верить». Без названий методов и
   профессиональных терминов: не «мотивационное интервьюирование помогает
   осознать необходимость фармакотерапии», а то, как человек сказал бы это
   родственнику пациента.
10. Не упоминай, что текст сгенерирован, и не обращайся к читателю.

Верни строго JSON по заданной схеме, без пояснений вокруг."
    };
}

