/// Схема ответа.
///
/// Поля `stated_age` и `stated_experience_years` — не для витрины. Модель
/// обязана явно повторить, какие числа она использовала: их сравнение с
/// параметрами даёт точную проверку расхождения, не полагающуюся на разбор прозы.
/// Целевая длина называется с запасом над порогом приёмки.
///
/// Без явного числа модель стабильно пишет у самой границы, и заметная доля
/// ответов отбраковывается на нескольких недостающих знаках — каждый такой
/// случай это полная перегенерация за деньги.
pub fn biography_schema_for(min_bio: usize, min_path: usize) -> serde_json::Value {
    let mut s = biography_schema();
    let props = &mut s["properties"];
    props["biography"]["description"] = serde_json::Value::String(format!(
        "Биография, 3-5 предложений, не короче {} знаков. Кто, откуда, как пришёл в профессию.",
        min_bio + 80
    ));
    props["professional_path"]["description"] = serde_json::Value::String(format!(
        "Профессиональный путь и подход к работе, 3-5 предложений, не короче {} знаков.",
        min_path + 80
    ));
    s
}

pub fn biography_schema() -> serde_json::Value {
    json!({
        "type": "object",
        "additionalProperties": false,
        "required": [
            "biography",
            "professional_path",
            "quote",
            "stated_age",
            "stated_experience_years"
        ],
        "properties": {
            "biography": {
                "type": "string",
                "description": "Биография, 3-5 предложений. Кто, откуда, как пришёл в профессию."
            },
            "professional_path": {
                "type": "string",
                "description": "Профессиональный путь и подход к работе, 3-5 предложений."
            },
            "quote": {
                "type": "string",
                "description": "Одна фраза от первого лица о своей работе. Без пафоса."
            },
            "stated_age": {
                "type": "integer",
                "description": "Возраст, который ты использовал. Должен совпасть с параметром."
            },
            "stated_experience_years": {
                "type": "integer",
                "description": "Стаж, который ты использовал. Должен совпасть с параметром."
            }
        }
    })
}

/// Собрать промпт портрета из визуальных параметров.
///
/// Кадр, поворот, взгляд, момент и техника съёмки приходят параметрами, а не
/// зашиты в шаблон: прежний шаблон требовал «погрудный кадр, взгляд в камеру»
/// у всех, и серия из восьми человек выглядела как фото на документы.
pub fn portrait_prompt(params_block: &str) -> String {
    format!(
        "Обычная фотография сотрудника реабилитационного центра для страницы \
         «Наши специалисты» на сайте центра. Её снял коллега или приглашённый \
         фотограф — не рекламная фотосессия и не художественный портрет.\n\n\
         Как снято: кадр, поворот, место в кадре, взгляд, момент и техника — \
         строго по описанию ниже. Цвет как у обычной камеры или телефона: \
         нейтральный баланс белого, без тонировки и цветокоррекции. Фон в резкости \
         или слегка размыт, как у телефона. Кожа естественная: видна, но не \
         подчёркнута. Лицо обычного человека своего возраста, не модели.\n\n\
         {params_block}"
    )
}
